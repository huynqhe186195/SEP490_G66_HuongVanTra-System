    Guid MaterialId,
    string MaterialName,
    string? MaterialUnitName,
    decimal Quantity,
    Guid? ComponentVariantId = null,
    string? ComponentSkuCode = null,
    string? ComponentVariantName = null,
    bool IsRequiredBaseComponent = false);

