    bool AllowRewardPoints,
    bool IsActive,
    string? ImageUrl,
    string? UnitName,
    decimal ConversionRate,
    Guid? BaseVariantId,
    bool IsBaseUnitVariant,
    bool IsAutoGeneratedSku,
    bool IsPurchasable,
    bool CanBeBomComponent,
    bool CanUseInCustom,
    bool CanHaveBom,
    bool HasBom,
    int BomLineCount,
    List<ProductUnitResponse> Units,
    List<BomLineResponse> BomLines);
