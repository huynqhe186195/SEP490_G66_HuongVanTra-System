-- Dụng cụ trà: thêm NL Piece (mua về) + BOM thành phẩm = NL x1 + BB-TEM-HVT x1
-- Ví dụ: HVT-XUC-TRE ← NL-XUC-TRE + BB-TEM-HVT
-- An toàn chạy lại (idempotent theo SkuCode cố định).
--
-- Windows PowerShell (tránh mất dấu):
--   docker cp backend/huongvantra_backend/Scripts/fix-tool-product-boms-with-nl.sql hvt-mysql:/tmp/fix-tool-boms.sql
--   docker exec hvt-mysql mysql -uhvtuser -phvtpass123 --default-character-set=utf8mb4 -e "source /tmp/fix-tool-boms.sql"
-- =============================================================================

SET NAMES utf8mb4;
SET time_zone = '+00:00';
SET @NOW = UTC_TIMESTAMP(6);

USE `hvt_product_db`;

SET @CAT_NL = 9206; -- Nguyen lieu san xuat
SET @TEM_VARIANT = (SELECT Id FROM ProductVariants WHERE SkuCode = 'BB-TEM-HVT' AND IsDeleted = 0 LIMIT 1);
SET @TEM_PRODUCT = (SELECT ProductId FROM ProductVariants WHERE Id = @TEM_VARIANT LIMIT 1);

-- Mapping: finished SKU → NL SKU / name / cost
DROP TEMPORARY TABLE IF EXISTS tmp_tool_nl;
CREATE TEMPORARY TABLE tmp_tool_nl (
  FinishedSku VARCHAR(50) PRIMARY KEY,
  NlSku VARCHAR(50) NOT NULL,
  NlName VARCHAR(255) NOT NULL,
  CostPrice DECIMAL(18,2) NOT NULL,
  MinStock INT NOT NULL,
  ProductId CHAR(36) NOT NULL,
  VariantId CHAR(36) NOT NULL
);

